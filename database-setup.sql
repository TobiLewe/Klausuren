-- Studium: dynamische Fristen und Klausuren ohne öffentliche Schreibrechte
-- In Supabase unter SQL Editor einmal vollständig ausführen.
-- Öffentliche Besucher können lesen. Einträge bitte über den Supabase Table Editor verwalten.

create table if not exists public.fristen (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null default '',
    category text not null default 'Frist',
    start_date date null,
    due_date date not null,
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

create unique index if not exists fristen_title_due_date_uidx
    on public.fristen (title, due_date);

create table if not exists public.klausuren (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null default '',
    exam_date date not null,
    exam_time text not null default '',
    location text not null default '',
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

alter table public.fristen enable row level security;
alter table public.klausuren enable row level security;

-- Vorhandene Policies werden entfernt, damit alte öffentliche Schreibrechte
-- auf diesen Tabellen nicht versehentlich bestehen bleiben.
do $$
declare p record;
begin
    for p in
        select schemaname, tablename, policyname
        from pg_policies
        where schemaname = 'public'
          and tablename in ('fristen', 'klausuren', 'gespeicherte_ansichten')
    loop
        execute format('drop policy if exists %I on %I.%I', p.policyname, p.schemaname, p.tablename);
    end loop;
end $$;

create policy fristen_public_read
    on public.fristen for select to anon, authenticated using (true);
create policy klausuren_public_read
    on public.klausuren for select to anon, authenticated using (true);

grant usage on schema public to anon, authenticated;
revoke all privileges on table public.fristen, public.klausuren from PUBLIC, anon, authenticated;
grant select on table public.fristen, public.klausuren to anon, authenticated;

-- Das alte SQL hatte pauschal Rechte auf alle Sequenzen in public vergeben.
-- Da die Website keine anonymen Schreibzugriffe mehr benötigt, diese Alt-Rechte entfernen.
revoke all privileges on all sequences in schema public from PUBLIC, anon, authenticated;

-- Die vorhandenen gemeinsamen Stundenplanansichten bleiben lesbar.
-- Schreiben/Ändern/Löschen über die anonyme Browser-API wird gesperrt.
-- Neue persönliche Ansichten werden vom Frontend lokal im jeweiligen Browser gespeichert.
DO $$
BEGIN
    IF to_regclass('public.gespeicherte_ansichten') IS NOT NULL THEN
        EXECUTE 'ALTER TABLE public.gespeicherte_ansichten ENABLE ROW LEVEL SECURITY';
        EXECUTE 'REVOKE ALL PRIVILEGES ON TABLE public.gespeicherte_ansichten FROM PUBLIC, anon, authenticated';
        EXECUTE 'GRANT SELECT ON TABLE public.gespeicherte_ansichten TO anon, authenticated';
        EXECUTE 'CREATE POLICY gespeicherte_ansichten_public_read ON public.gespeicherte_ansichten FOR SELECT TO anon, authenticated USING (true)';
    END IF;
END $$;

