    on public.fristen (title, due_date);

create table if not exists public.klausuren (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null default '',
    exam_date date not null,
    exam_time text not null default '',
    location text not null default '',
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 2. Projektideen: vorhandene Einträge bleiben bestehen
-- ------------------------------------------------------------
create schema if not exists studium_private;
revoke all privileges on schema studium_private from PUBLIC, anon, authenticated;

create table if not exists public.projekt_mitglieder (
    user_id uuid primary key references auth.users(id) on delete cascade,
    display_name text not null check (length(btrim(display_name)) between 1 and 80),
    created_at timestamptz not null default now()
);

create table if not exists public.projektideen (
    id bigint generated by default as identity primary key,
    slot_number smallint not null unique check (slot_number between 1 and 6),
    user_id uuid references auth.users(id) on delete set null,
    person_name text not null check (length(btrim(person_name)) between 1 and 80),
    title text not null check (length(btrim(title)) between 1 and 120),
    description text not null check (length(btrim(description)) between 1 and 2000),
    implementation text not null default '' check (length(implementation) <= 2000),
    created_at timestamptz not null default now()
);

alter table public.projektideen
    add column if not exists user_id uuid references auth.users(id) on delete set null;

-- The shared-password version does not use Supabase user identities.
alter table public.projektideen alter column user_id drop not null;
drop index if exists public.projektideen_one_per_user_uidx;
drop trigger if exists prepare_projektidee_insert on public.projektideen;
drop function if exists studium_private.prepare_projektidee_insert();

-- ------------------------------------------------------------
-- 3. RLS aktivieren und bisherige Policies entfernen
-- ------------------------------------------------------------
alter table public.fristen enable row level security;
alter table public.klausuren enable row level security;
alter table public.projektideen enable row level security;
alter table public.projekt_mitglieder enable row level security;

do $$
declare
    p record;
begin
    for p in
        select schemaname, tablename, policyname
        from pg_policies
        where schemaname = 'public'
          and tablename in (
              'fristen', 'klausuren', 'gespeicherte_ansichten',
              'projektideen', 'projekt_mitglieder'
          )
    loop
        execute format(
            'drop policy if exists %I on %I.%I',
            p.policyname, p.schemaname, p.tablename
        );
    end loop;
end $$;

