-- ------------------------------------------------------------
-- 5. Private Passwortspeicher und Passwort-Hash-Funktionen
-- ------------------------------------------------------------
create schema if not exists studium_private;
revoke all privileges on schema studium_private from PUBLIC, anon, authenticated;

create table if not exists studium_private.project_settings (
    singleton boolean primary key default true check (singleton = true),
    password_hash text not null,
    updated_at timestamptz not null default now()
);
revoke all privileges on table studium_private.project_settings from PUBLIC, anon, authenticated;

-- pgcrypto is used for bcrypt. If it already exists, use its current schema.
create schema if not exists extensions;
do $$
declare
    v_crypto_schema text;
begin
    select n.nspname
      into v_crypto_schema
      from pg_extension e
      join pg_namespace n on n.oid = e.extnamespace
     where e.extname = 'pgcrypto';

    if v_crypto_schema is null then
        execute 'create extension pgcrypto with schema extensions';
        v_crypto_schema := 'extensions';
    end if;

    execute format($ddl$
        create or replace function studium_private.hash_project_password(p_password text)
        returns text
        language sql
        security definer
        set search_path = ''
        as $fn$
            select %I.crypt(p_password, %I.gen_salt('bf', 12))
        $fn$;
    $ddl$, v_crypto_schema, v_crypto_schema);

    execute format($ddl$
        create or replace function studium_private.match_project_password(p_password text, p_hash text)
        returns boolean
        language sql
        security definer
        set search_path = ''
        as $fn$
            select coalesce(%I.crypt(p_password, p_hash) = p_hash, false)
        $fn$;
    $ddl$, v_crypto_schema);
end $$;

create or replace function studium_private.set_project_password(p_password text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    if p_password is null
       or pg_catalog.length(p_password) < 10
       or pg_catalog.octet_length(pg_catalog.convert_to(p_password, 'UTF8')) > 72 then
        raise exception using message = 'Das Gruppenpasswort muss mindestens 10 Zeichen und darf höchstens 72 UTF-8-Bytes lang sein.', errcode = '22023';
    end if;

    insert into studium_private.project_settings (singleton, password_hash, updated_at)
    values (true, studium_private.hash_project_password(p_password), pg_catalog.now())
    on conflict (singleton) do update
        set password_hash = excluded.password_hash,
            updated_at = excluded.updated_at;
end;
$$;

create or replace function studium_private.check_project_password(p_password text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_hash text;
begin
    select s.password_hash
      into v_hash
      from studium_private.project_settings s
     where s.singleton = true;

    if v_hash is null then
        raise exception using message = 'Das Gruppenpasswort wurde noch nicht eingerichtet.', errcode = '55000';
    end if;

    if not studium_private.match_project_password(coalesce(p_password, ''), v_hash) then
        raise exception using message = 'Das Gruppenpasswort ist falsch.', errcode = '28000';
    end if;
end;
$$;

revoke all privileges on function studium_private.hash_project_password(text) from PUBLIC, anon, authenticated;
revoke all privileges on function studium_private.match_project_password(text, text) from PUBLIC, anon, authenticated;
revoke all privileges on function studium_private.set_project_password(text) from PUBLIC, anon, authenticated;
revoke all privileges on function studium_private.check_project_password(text) from PUBLIC, anon, authenticated;

-- ------------------------------------------------------------
-- 6. Öffentliche RPC-Endpunkte: Passwort wird serverseitig geprüft
-- ------------------------------------------------------------
create or replace function public.get_projektideen(p_password text)
returns table (
    id bigint,
    slot_number smallint,
    person_name text,
    title text,
    description text,
    implementation text,
    created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
    perform studium_private.check_project_password(p_password);

    return query
        select pi.id, pi.slot_number, pi.person_name, pi.title,
               pi.description, pi.implementation, pi.created_at
          from public.projektideen pi
         order by pi.slot_number asc;
end;
$$;

create or replace function public.submit_projektidee(
    p_password text,
    p_person_name text,
    p_title text,
    p_description text,
    p_implementation text default ''
)
returns table (
    id bigint,
    slot_number smallint,
    person_name text,
    title text,
    description text,
    implementation text,
    created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_slot smallint;
    v_id bigint;
    v_name text;
    v_title text;
    v_description text;
    v_implementation text;
begin
    perform studium_private.check_project_password(p_password);

    v_name := pg_catalog.btrim(coalesce(p_person_name, ''));
    v_title := pg_catalog.btrim(coalesce(p_title, ''));
    v_description := pg_catalog.btrim(coalesce(p_description, ''));
    v_implementation := coalesce(p_implementation, '');

    if pg_catalog.length(v_name) not between 1 and 80 then
        raise exception using message = 'Bitte gib einen Namen mit maximal 80 Zeichen ein.', errcode = '22023';
    end if;
    if pg_catalog.length(v_title) not between 1 and 120 then
        raise exception using message = 'Der Titel muss zwischen 1 und 120 Zeichen lang sein.', errcode = '22023';
    end if;
    if pg_catalog.length(v_description) not between 1 and 2000 then
        raise exception using message = 'Die Beschreibung muss zwischen 1 und 2000 Zeichen lang sein.', errcode = '22023';
    end if;
    if pg_catalog.length(v_implementation) > 2000 then
        raise exception using message = 'Die Angaben zur Umsetzung dürfen höchstens 2000 Zeichen lang sein.', errcode = '22023';
    end if;

    -- Serialisiert Einreichungen, damit bei nahezu zeitgleichen Klicks keine Plätze doppelt vergeben werden.
    perform pg_catalog.pg_advisory_xact_lock(2026101506::bigint);

    if exists (
        select 1 from public.projektideen pi
        where pg_catalog.lower(pg_catalog.btrim(pi.person_name)) = pg_catalog.lower(v_name)
    ) then
        raise exception using message = 'Für diesen Namen wurde bereits eine Idee eingetragen.', errcode = '23505';
    end if;

    select candidate.slot_number::smallint
      into v_slot
      from pg_catalog.generate_series(1, 6) as candidate(slot_number)
     where not exists (
         select 1 from public.projektideen pi
         where pi.slot_number = candidate.slot_number
     )
     order by candidate.slot_number
     limit 1;

    if v_slot is null then
        raise exception using message = 'Alle sechs Plätze sind bereits belegt.', errcode = '23514';
    end if;

    insert into public.projektideen as inserted_idea
        (slot_number, user_id, person_name, title, description, implementation, created_at)
    values
        (v_slot, null, v_name, v_title, v_description, v_implementation, pg_catalog.now())
    returning inserted_idea.id into v_id;

    return query
        select pi.id, pi.slot_number, pi.person_name, pi.title,
               pi.description, pi.implementation, pi.created_at
          from public.projektideen pi
         where pi.id = v_id;
end;
$$;

revoke all privileges on function public.get_projektideen(text) from PUBLIC, anon, authenticated;
revoke all privileges on function public.submit_projektidee(text, text, text, text, text) from PUBLIC, anon, authenticated;
grant execute on function public.get_projektideen(text) to anon, authenticated;
grant execute on function public.submit_projektidee(text, text, text, text, text) to anon, authenticated;

